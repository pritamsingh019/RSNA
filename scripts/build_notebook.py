"""Generate a self-contained Kaggle access-check notebook from the source module."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def build_notebook() -> dict:
    module_bytes = (ROOT / "rsna_knee" / "data_access.py").read_bytes()
    source = module_bytes.decode("utf-8")
    guard = '\nif __name__ == "__main__":\n    raise SystemExit(main())\n'
    if not source.endswith(guard):
        raise ValueError("Module entry-point guard changed; review notebook embedding")
    embedded = source.removesuffix(guard)
    source_sha = hashlib.sha256(module_bytes).hexdigest()

    def markdown(cell_id: str, value: str) -> dict:
        return {"cell_type": "markdown", "id": cell_id, "metadata": {}, "source": value.splitlines(True)}

    def code(cell_id: str, value: str) -> dict:
        return {"cell_type": "code", "id": cell_id, "metadata": {},
                "execution_count": None, "outputs": [], "source": value.splitlines(True)}

    return {
        "nbformat": 4, "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
            "rsna_knee": {"phase": "A", "module_sha256": source_sha,
                          "embedded_cell_sha256": hashlib.sha256(embedded.encode("utf-8")).hexdigest()},
        },
        "cells": [
            markdown("purpose", "# RSNA Knee: attached-input access check\n\n"
                     "Generated by `scripts/build_notebook.py` from `rsna_knee/data_access.py`.\n\n"
                     "Phase A only: verify attached manifest paths and save runtime evidence. "
                     "CSV contents, labels, reports, DICOM headers, decoding, and model training "
                     "are pending later reviewed phases. This is not a submission notebook.\n\n"
                     "In the Kaggle browser, review/accept the competition rules, import this notebook, "
                     "attach the competition input, select CPU/no accelerator, set Internet Off, "
                     "and use Save Version → Save & Run All. No CLI, install, or API token is needed.\n"),
            code("configuration", "from pathlib import Path\n\n"
                 "INPUT_BASE = Path('/kaggle/input')\n"
                 "# If discovery is ambiguous, set this to the displayed competition path.\n"
                 "DATA_ROOT = None\n"
                 "OUTPUT_DIR = Path('/kaggle/working/rsna_audit')\n"
                 f"SOURCE_SHA256 = {source_sha!r}\n"),
            markdown("module-note", "The next cell embeds the reviewed local module so a single `.ipynb` "
                     "can run offline without attaching the source repository. Rebuild this file "
                     "after changing the module; edit the module rather than this generated cell.\n"),
            code("access-module", embedded),
            code("run-check", "report, report_path = run_access_check(\n"
                 "    INPUT_BASE, OUTPUT_DIR, explicit_root=DATA_ROOT, source_sha256=SOURCE_SHA256\n"
                 ")\n"
                 "print(json.dumps({\n"
                 "    'status': report['discovery']['status'],\n"
                 "    'selected_root': report['discovery']['selected_root'],\n"
                 "    'report_path': str(report_path),\n"
                 "    'phase1_pass': report['phase1_pass'],\n"
                 "    'elapsed_seconds': report['duration_before_report_write_seconds'],\n"
                 "}, indent=2))\n"),
            markdown("stop", "## Stop and review\n\n"
                     "Download only the small `access_check_*.json` output under `rsna_audit/`. "
                     "`MANIFESTS_LOCATED_AUDIT_PENDING` establishes file presence in this runtime, "
                     "not label quality, image integrity, account permissions, or Phase 1 PASS. "
                     "Any missing, ambiguous, or incomplete discovery needs review. "
                     "Next: implement and run Phase B's schema/label-coverage and DICOM audit.\n"),
        ],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "notebooks" / "kaggle_access_check.ipynb")
    args = parser.parse_args()
    notebook = build_notebook()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(notebook, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"Generated {args.output} ({args.output.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
